#include <string>
#include <sys/time.h>
#include <sys/types.h>
//---------------------------------------------------------------------------------------------------------------------
// Struct to store file attributes to be returned with *stat*() calls
struct FileAttributes
{
    bool                    isDir;
    off64_t                 size;
    timespec                aTime;
    timespec                mTime;
    timespec                cTime;
    std::string             version;
};
