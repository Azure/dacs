#pragma once
//---------------------------------------------------------------------------------------------------------------------
#include <curl/curl.h>
//---------------------------------------------------------------------------------------------------------------------
struct CurlHandle
{
    CURL* pHandle = NULL;
    CurlHandle()
    {
        pHandle = curl_easy_init();
    };

    ~CurlHandle()
    {
        curl_easy_cleanup(pHandle);
        pHandle = NULL;
    };
};
