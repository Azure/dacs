/*
 * Azure Blob Cache Provider — Storage Intercept Wrapper
 *
 * Implements the blob_read() contract for Azure Blob cache providers.
 * Internally uses DACS's SI_open/SI_pread/SI_close C API to serve
 * cached blob data through the DACS distributed caching system.
 *
 * DACS handles cache misses internally — on a miss it fetches from
 * Azure Blob Storage, populates the cache, and returns the data.
 *
 * The __attribute__((constructor)) function auto-generates the SI config
 * on first load (dlopen), so no manual config is needed.
 */

