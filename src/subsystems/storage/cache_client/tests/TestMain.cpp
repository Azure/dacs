#include "gtest/gtest.h"
#include <cstdlib> // for srand
#include <ctime>   // for time

#include "CacheClientLogger.h"
//--------------------------------------------------------------------------------------------------------------------------------------------
int main(int argc, char** argv)
{
    srand(time(nullptr));
    LoggingApi::Init();
    LoggingApi::FlushCachedLog();
    ::testing::InitGoogleTest(&argc, argv);
    return RUN_ALL_TESTS();
}
